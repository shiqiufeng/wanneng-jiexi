"""解析帮助文案

`/解析帮助` 命令的输出集中在本模块维护，
避免帮助内容散落在 main.py、README.md、metadata.yaml 三处各写一份。
"""

from __future__ import annotations

DIVIDER = "━━━━━━━━━━━━━━━━"

HEADER = f"📖 万能解析 · 使用帮助\n{DIVIDER}"


def build_help(platforms: list[str], album_name: str = "") -> str:
    """拼装帮助文本

    Args:
        platforms (list[str]): 当前已启用的平台显示名称，按启用顺序传入
        album_name (str): 默认群相册名（命令里没写相册名时用它）

    Returns:
        str: 可直接发送的纯文本帮助
    """
    platform_line = "、".join(platforms) if platforms else "（当前无已启用平台，请在配置面板开启）"
    album_label = album_name or "少女集"

    return "\n".join(
        [
            HEADER,
            "",
            "【基础用法】",
            "把受支持平台的分享链接直接发进会话，机器人会自动解析并回传",
            "视频 / 图集 / 音频，并附带信息卡片。无需任何前缀。",
            "",
            "【当前已启用平台】",
            platform_line,
            "",
            "【命令一览】",
            "/音乐 <链接>            仅解析音频，只发音频不发视频",
            "/全部 <主页链接>        抖音主页作品清单（卡片 + 作品直链）",
            "/全部音乐 <主页链接>    抖音主页音乐清单（音频直链文本）",
            "/全部相册<名字> <主页>      把主页每个作品都存进群相册，一个作品一条",
            "                            例：/全部相册旅游 <主页链接>",
            f"                            不写名字则用默认相册「{album_label}」",
            "/相册<名字> <链接>      解析后直接存进群相册，不发到会话",
            "                        例：/相册旅游 <链接> 存进「旅游」相册",
            f"                        不写名字则存进默认相册「{album_label}」",
            "/相册列表               列出群内所有相册名（对照用）",
            "/创建相册<名字>        新建群相册（群主 / 群管理员 / 相册所有者）",
            "/删除相册<名字>        删除群相册（仅相册所有者本人）",
            "/开启解析               开启当前会话的解析（管理员）",
            "/关闭解析               关闭当前会话的解析（管理员）",
            "/短链验证               自检短链服务是否可用（管理员）",
            "/相册自检               检查群相册是否已就绪（管理员）",
            "/登录B站                扫码登录 B 站（管理员）",
            "/解析帮助               显示本帮助（斜杠可省略，也认 /帮助）",
            "",
            "【可选参数】顺序不限，紧跟在命令后即可",
            "· 条数：1-200，如「/全部 10 <链接>」",
            "· 发送方式：文件 / 语音，如「/音乐 文件 <链接>」",
            "· 可组合：「/全部音乐 语音 10 <主页链接>」",
            "· /全部相册 的条数上限为 50（每个作品都要完整下载一遍）",
            "",
            "【实况说明】",
            "抖音、小红书、TikTok 的实况图会以 mp4 发送，并替代对应的静态图；",
            "分段作品的实况与静态图各归其位。快手图集暂只发静态图。",
            "",
            "【群相册】",
            "「/相册<名字> + 链接」把解析出的图片和视频存进同名群相册，只回一条",
            "上传结果，不往群里发媒体本身；名字省略时用默认相册"
            f"「{album_label}」。",
            "「/全部相册<名字> + 主页链接」把该主页的每个作品逐个存进相册，",
            "一个作品在相册里成一条（图片合并成一条说说，视频各自成贴）；",
            "命令开头与结尾各回一条，中间不刷屏。",
            "同一作品的多张图片会合并成相册里的同一条说说；视频在相册里各成一条",
            "（视频接口不带批次号，协议上没法并进同一条）。",
            "作品文案默认不写进相册：电脑版 QQ 看不到群相册评论，且 NapCat",
            "≤ v4.18.38 的评论接口必定报错。确需时可在配置里打开",
            "「把文案写入相册评论」，写失败会如实说明原因。",
            "",
            "【相册管理】",
            "· /相册列表 先看看群里有哪些相册，名字要写得完全一致",
            "· /创建相册<名字>：群主、群管理员与相册所有者可用",
            "· /删除相册<名字>：只有相册所有者本人可用",
            "· 建/删相册优先走协议端的相册接口；NapCat 没暴露该接口时，会自动",
            "  改走原始发包（需在 NapCat 配置里启用 packetBackend）。两种情况",
            "  都以「重新拉一次相册列表」为准，绝不会假装建好了；实在不行会",
            "  如实回报原因，并提示到群相册里手动新建或删除（只需一次）",
            "· 上传结果不对劲先跑 /相册自检，逐项探测上传接口与相册是否可达",
            "",
            "【小提示】",
            "· 音频文件名形如「作者_歌名.mp3」，便于区分",
            "· 配置短链服务后，清单里的直链会自动转成短链",
            "· 群聊中可与其它 Bot 共存，贴表情仲裁避免重复解析",
            DIVIDER,
        ]
    )
